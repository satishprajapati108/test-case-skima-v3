// ---------- generic filler ----------
const log = (w, ...a) => console.log(`[${w}]`, ...a);

async function pickSelect(page, g) {
  if (await g.locator('.ant-select-selection-item').count()) return false;
  const sel = g.locator('.ant-select-selector').first();
  if (!(await sel.count())) return false;
  await sel.click({ timeout: 3000 }).catch(() => {});
  const opt = page.locator('.ant-select-dropdown:not(.ant-select-dropdown-hidden) .ant-select-item-option:not(.ant-select-item-option-disabled)').first();
  try { await opt.waitFor({ timeout: 3000 }); } catch { await page.keyboard.press('Escape'); return false; }
  await opt.click();
  return true;
}

async function pickRadio(g, label) {
  const radios = g.locator('input[type=radio]');
  const n = await radios.count();
  if (!n) return false;
  for (let i = 0; i < n; i++) if (await radios.nth(i).isChecked()) return false;
  const texts = [];
  for (let i = 0; i < n; i++) texts.push(((await radios.nth(i).evaluate(e => (e.closest('label')?.innerText || e.parentElement?.parentElement?.innerText || '')))).trim());
  const no = /disabled|legal|case|member of|previously worked|currently hold|worked outside|relative|vendor|dependent/i.test(label);
  let idx = texts.findIndex(t => /fresher/i.test(t));
  if (idx < 0) idx = texts.findIndex(t => /father/i.test(t));
  if (idx < 0) idx = texts.findIndex(t => (no ? /^no/i : /^yes/i).test(t));
  if (idx < 0) idx = 0;
  const r = radios.nth(idx);
  await r.evaluate(e => (e.closest('label') || e).click());
  return true;
}

async function fillGroups(page, root, w, filled) {
  const groups = root.locator('div.group');
  const n = await groups.count();
  let changed = 0;
  for (let i = 0; i < n; i++) {
    const g = groups.nth(i);
    if (!(await g.isVisible().catch(() => false))) continue;
    if (await g.locator('div.group').count()) continue; // nested container
    const label = ((await g.locator('label').first().innerText().catch(() => '')) || '').replace(/\*/g, '').trim();
    const key = `${label}#${i}`;
    try {
      // file upload
      const file = g.locator('input[type=file]');
      if (await file.count()) {
        if (!filled.has(key)) {
          filled.add(key);
          await file.first().setInputFiles(fileFor(label));
          await page.waitForTimeout(1500);
          changed++;
        }
        continue;
      }
      if (await g.locator('.ant-select').count()) { if (await pickSelect(page, g)) changed++; continue; }
      if (await g.locator('input[type=radio]').count()) { if (await pickRadio(g, label)) changed++; continue; }
      const cb = g.locator('input[type=checkbox]');
      if (await cb.count()) { if (!(await cb.first().isChecked())) { await cb.first().evaluate(e => (e.closest('label') || e).click()); changed++; } continue; }
      const txt = g.locator('textarea, input:not([type=hidden]):not([type=search]):not([type=file])').first();
      if (!(await txt.count())) continue;
      const cur = await txt.inputValue();
      if (cur && !['Test', 'Test Corp Pvt Ltd'].includes(cur) && !(/name/i.test(label) && /passport/i.test(label) && cur === 'A1234567')) continue;
      const ph = (await txt.getAttribute('placeholder')) || '';
      const type = (await txt.getAttribute('type')) || 'text';
      if (/date/i.test(ph) || /\bdate\b/i.test(label) || /date|dob|birth|from|to\b|stay/i.test(label) && /select/i.test(ph)) {
        await txt.click();
        await txt.fill(/valid|expir|till|\bto\b/i.test(label) ? '2032-01-15' : '2020-01-15');
        await page.keyboard.press('Enter');
        await page.keyboard.press('Escape');
      } else {
        await txt.fill(valueFor(label, ph, type));
      }
      changed++;
    } catch (e) { log(w, `  ! ${label}: ${e.message.split('\n')[0]}`); }
  }
  return changed;
}

async function fillUntilStable(page, root, w, filled = new Set()) {
  for (let pass = 0; pass < 6; pass++) {
    const c = await fillGroups(page, root, w, filled);
    if (!c) break;
    await page.waitForTimeout(300);
  }
}

async function handleRepeaters(page, w) {
  for (let rounds = 0; rounds < 2; rounds++) {
    const add = page.getByRole('button', { name: /add more/i }).first();
    if (!(await add.count()) || !(await add.isVisible())) return;
    if (!(await page.getByText('None added yet').count())) return; // already has entries
    await add.click();
    const dlg = page.locator('.ant-modal-content, .ant-drawer-content, [role=dialog]').last();
    try { await dlg.waitFor({ timeout: 4000 }); } catch { log(w, '  ! no dialog after Add more'); return; }
    await fillUntilStable(page, dlg, w);
    const save = dlg.locator('button[type=submit], button:has-text("Save"), button:has-text("Add"), button:has-text("Done")').last();
    await save.click();
    await page.waitForTimeout(1500);
    if (await dlg.isVisible().catch(() => false)) {
      const errs = await dlg.locator('.text-red-600, .text-red-500, .ant-form-item-explain-error, [role=alert]').allInnerTexts();
      log(w, '  ! repeater dialog still open:', errs.slice(0, 4).join(' | '));
      await page.screenshot({ path: path.join(SHOTS, `err-dialog-${Date.now()}.png`) });
      await page.keyboard.press('Escape');
    }
  }
}

async function openList(page) {
  if (!(await page.getByText('Document Requested').count())) {
    await page.getByRole('button', { name: /back to categories/i }).click().catch(() => {});
  }
  await page.waitForSelector('text=Document Requested', { timeout: 60000 });
}

async function doSection(page, title, w) {
  await openList(page);
  await page.getByRole('heading', { name: title, exact: true }).first().click();
  await page.waitForSelector('form', { timeout: 15000 });
  await page.waitForTimeout(800);
  const form = page.locator('form').first();
  const filled = new Set();
  await fillUntilStable(page, form, w, filled);
  await handleRepeaters(page, w);
  await fillUntilStable(page, form, w, filled);
  await page.getByRole('button', { name: /save & continue/i }).first().click();
  await page.waitForTimeout(2500);
  const errs = await page.locator('form .text-red-600:not(:has(*)), form .ant-form-item-explain-error').allInnerTexts().catch(() => []);
  const realErrs = errs.map(s => s.trim()).filter(s => s && s !== '*');
  const safe = title.replace(/\W+/g, '_');
  await page.screenshot({ path: path.join(SHOTS, `${safe}.png`), fullPage: true });
  return realErrs;
}

(async () => {
  fs.mkdirSync(SHOTS, { recursive: true });
  const browser = await chromium.launch({ headless: !HEADED, slowMo: HEADED ? 150 : 0 });
  await makeDocs(browser);
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  ctx.setDefaultTimeout(8000);
  const first = await ctx.newPage();
  await first.goto(URL);
  await first.waitForSelector('text=Document Requested', { timeout: 60000 });
  const finalUrl = first.url(); // reuse resolved URL (skips the tracking redirect)
  // Sections vary per candidate/time: always read the cards actually shown on the page.
  const discover = async pg => {
    await openList(pg);
    await pg.waitForTimeout(800);
    let s = (await pg.$$eval('button h1,button h2,button h3,button h4,button h5,button h6', els => els.map(e => e.textContent.trim())))
      .filter(t => t && t !== 'Document Requested');
    s = [...new Set(s)];
    return ONLY.length ? s.filter(x => ONLY.includes(x)) : s;
  };
  const results = {};
  const worker = async (id, queue) => {
    const page = id === 0 ? first : await ctx.newPage();
    if (id !== 0) await page.goto(finalUrl);
    while (queue.length) {
      const s = queue.shift();
      const t0 = Date.now();
      try {
        const errs = await doSection(page, s, id);
        results[s] = errs.length ? { status: 'validation-errors', errs } : { status: 'saved' };
        log(id, `${errs.length ? '✗' : '✓'} ${s} (${((Date.now() - t0) / 1000).toFixed(1)}s) ${errs.slice(0, 3).join(' | ')}`);
      } catch (e) {
        results[s] = { status: 'failed', err: e.message.split('\n')[0] };
        log(id, `✗ ${s}: ${e.message.split('\n')[0]}`);
        await page.goto(finalUrl).catch(() => {});
      }
    }
    if (id !== 0) await page.close();
  };
  // Rounds: fill everything visible; re-scan (new sections can appear after saving); retry failures.
  for (let round = 1; round <= 3; round++) {
    const all = await discover(first);
    const pending = round === 1 ? all : all.filter(s => !results[s] || results[s].status !== 'saved');
    console.log(`Round ${round}: ${all.length} sections visible, ${pending.length} to fill`);
    if (!pending.length) break;
    const queue = [...pending];
    await Promise.all(Array.from({ length: Math.min(WORKERS, pending.length) }, (_, i) => worker(i, queue)));
  }
  console.log(`Processed ${Object.keys(results).length} sections`);

  // final overview
  await first.goto(finalUrl);
  await first.waitForSelector('text=Document Requested');
  await first.waitForTimeout(1500);
  await first.screenshot({ path: path.join(SHOTS, '00-overview.png'), fullPage: true });
  const summary = await first.locator('text=/\\d+\\/\\d+/').first().innerText().catch(() => '?');
  console.log('Sections complete:', summary);
  fs.writeFileSync('report.json', JSON.stringify({ summary, results }, null, 2));
  if (process.env.SUBMIT) {
    await first.getByRole('button', { name: /submit document/i }).click();
    await first.waitForTimeout(3000);
    await first.screenshot({ path: path.join(SHOTS, '99-submitted.png'), fullPage: true });
  }
  await browser.close();
})();
