/**
 * Skima candidate-document-upload auto-filler (Playwright).
 *   npm run fill                 -> headless, 5 parallel workers
 *   HEADED=1 npm run fill        -> watch it run
 *   WORKERS=8 npm run fill       -> more parallelism
 *   ONLY="Passport Details,Medical Data" npm run fill   -> subset of sections
 * Uses DUMMY test data + generated sample documents. Does NOT click the final "Submit Document".
 * Set SUBMIT=1 to also submit at the end.
 */
const { chromium } = require('@playwright/test');
const fs = require('fs');
const path = require('path');

const URL = process.env.FORM_URL ||
  'https://tracking.eu.nylas.com/l/e2f044e830cb45aa94e04651af85cb0e/0/8a7af6246ad75ecdb8dcc90652ad518f4b67072bf1a9ccdaa47c7182c9858ba9?cache_buster=1793714885';
const WORKERS = +(process.env.WORKERS || 5);
const HEADED = !!process.env.HEADED;
const ONLY = (process.env.ONLY || '').split(',').map(s => s.trim()).filter(Boolean);
const DOCS = path.resolve('docs');
const SHOTS = path.resolve('shots');
const EMAIL = 'satish.prajapati@skima.ai';

// ---------- sample documents ----------
async function makeDocs(browser) {
  fs.mkdirSync(DOCS, { recursive: true });
  if (fs.existsSync(path.join(DOCS, 'sample.pdf'))) return;
  const p = await browser.newPage({ viewport: { width: 400, height: 500 } });
  await p.setContent(`<body style="margin:0;display:grid;place-items:center;height:100vh;background:#cfe3ff;font:bold 28px sans-serif">
    <div style="text-align:center"><div style="width:180px;height:180px;border-radius:50%;background:#4a7bd6;margin:auto"></div><p>TEST PHOTO</p></div></body>`);
  await p.screenshot({ path: path.join(DOCS, 'photo.png') });
  await p.screenshot({ path: path.join(DOCS, 'photo.jpg'), type: 'jpeg' });
  await p.setContent('<body style="font:20px sans-serif;padding:40px"><h1>SAMPLE TEST DOCUMENT</h1><p>Generated by Playwright for automated form testing. Not a real document.</p></body>');
  await p.pdf({ path: path.join(DOCS, 'sample.pdf'), format: 'A4' });
  await p.close();
}
const fileFor = label => /photo|image|picture/i.test(label) ? path.join(DOCS, 'photo.png') : path.join(DOCS, 'sample.pdf');

